"""Generate Pesadithi's dark theme from the light stylesheet.
Rewrites the block between /* DARK:START */ and /* DARK:END */ in app/pesadithi.css.
Dark is neutral charcoal (not green), opt-in via html[data-theme="dark"].
Usage: python3 tools/theme/build_dark.py"""
import colorsys, os, re
P = os.path.join(os.path.dirname(__file__), '..', '..', 'app', 'pesadithi.css')
css = open(P).read()
css = re.sub(r'\n?/\* DARK:START.*?/\* DARK:END \*/\n?', '\n', css, flags=re.S)
D = 'html[data-theme="dark"]'
SKIP = ('.sm', '.dev', '.phonewrap', '.share-card', '.sc-', '.share-strip', '.receipt', '.rl', '.rh', '.rf', '.rc', '.tally4', '.skip', '@font-face')

def hx(c):
    c = c.lstrip('#'); c = ''.join(ch * 2 for ch in c) if len(c) == 3 else c
    return tuple(int(c[i:i + 2], 16) / 255 for i in (0, 2, 4))
def out(rgb): return '#%02x%02x%02x' % tuple(max(0, min(255, round(v * 255))) for v in rgb)
def lum(rgb): r, g, b = rgb; return 0.2126 * r + 0.7152 * g + 0.0722 * b

def bg(c):  # light surfaces -> charcoal, keeping a hint of hue
    rgb = hx(c); h, l, s = colorsys.rgb_to_hls(*rgb)
    if lum(rgb) < 0.55: return None
    return out(colorsys.hls_to_rgb(h, 0.075 + (1 - l) * 0.75, min(s, 1) * 0.28))
def fg(c):  # dark text -> light text; mid colours brightened
    rgb = hx(c); h, l, s = colorsys.rgb_to_hls(*rgb)
    if lum(rgb) > 0.7: return None
    if s < 0.25: return out(colorsys.hls_to_rgb(h, min(0.95, 1.02 - l * 0.85), s * 0.6))
    return out(colorsys.hls_to_rgb(h, max(l, 0.66), min(1, s * 0.95)))
def border(c):
    rgb = hx(c); h, l, s = colorsys.rgb_to_hls(*rgb)
    if lum(rgb) < 0.5: return None
    return out(colorsys.hls_to_rgb(h, 0.17 + (1 - l) * 0.6, s * 0.25))

HEX = re.compile(r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b')
def mapv(prop, val):
    prop = prop.strip()
    if 'rgba(255,255,255' in val.replace(' ', '') and prop.startswith('background'):
        return re.sub(r'rgba\(\s*255\s*,\s*255\s*,\s*255', 'rgba(18,20,22', val)
    if prop.startswith('background'): f = bg
    elif prop in ('color', 'fill', 'stroke', 'caret-color', 'text-decoration-color', 'outline-color'): f = fg
    elif prop.startswith('border') or prop == 'outline': f = border
    elif prop == 'box-shadow': f = lambda c: '#2c3236' if lum(hx(c)) > 0.6 else None
    else: return None
    changed = False
    def rep(m):
        nonlocal changed
        r = f(m.group(0))
        if r: changed = True; return r
        return m.group(0)
    nv = HEX.sub(rep, val)
    return nv if changed else None

rules = []
for m in re.finditer(r'([^{}@]+)\{([^{}]*)\}', css):
    sel, body = m.group(1).strip(), m.group(2)
    if not sel or sel.startswith(':root') or any(k in sel for k in SKIP) or sel.startswith('from') or sel.startswith('to') or re.match(r'^\d', sel): continue
    decls = []
    for d in body.split(';'):
        if ':' not in d or d.strip().startswith('--'): continue
        p, v = d.split(':', 1)
        nv = mapv(p, v)
        if nv: decls.append(f'{p.strip()}:{nv.strip()}')
    if decls:
        sels = ', '.join(f'{D} {s.strip()}' for s in sel.split(','))
        rules.append(f'{sels} {{ {"; ".join(decls)}; }}')

VARS = {'--bg': '#121416', '--ink': '#eef2f0', '--text': '#d5dcd9', '--muted': '#9ba6a2', '--faint': '#8d9894', '--line': '#2b3033', '--ctl': '#4b5357',
        '--panel': '#1a1d20', '--panel2': '#212529', '--soft': '#1a1d20', '--mint': '#1b2621', '--brand': '#56c596', '--brand-dk': '#7fd6ae', '--brand-tint': '#1b2621', '--brand-tint2': '#24372e',
        '--leaf': '#6dbb95', '--in': '#36a865', '--out': '#ee5a4c', '--credit': '#7f97f0', '--loan': '#cf8519', '--fee': '#a4adb5', '--bad': '#ff8a80', '--good': '#36a865', '--focus': '#56c596',
        '--in-tint': '#16281d', '--out-tint': '#2e1916', '--credit-tint': '#1a2033'}
LIGHT = re.search(r':root\s*\{([^}]*)\}', css).group(1)
light_vars = '; '.join(d.strip() for d in LIGHT.split(';') if d.strip().startswith('--') and not d.strip().startswith(('--serif', '--sans', '--mono', '--r:', '--wrap')))
block = ['/* DARK:START (generated by tools/theme/build_dark.py; do not edit by hand) */',
         f'{D} {{ color-scheme: dark; {"; ".join(f"{k}: {v}" for k, v in VARS.items())}; }}',
         f'{D} body {{ background: var(--bg); }}',
         *rules,
         # light islands: story mode, the phone and the share card keep their light look
         f'{D} .sm, {D} .dev, {D} .share-card, {D} .receipt {{ {light_vars}; color: var(--text); }}',
         f'{D} .receipt {{ background: #fff; box-shadow: 8px 8px 0 #24372e; }}',
         f'{D} .roles button[aria-selected="true"], {D} .periods button[aria-pressed="true"], {D} .choices:not(.opts) button[aria-pressed="true"], {D} .storynav a.on {{ background: var(--ink); border-color: var(--ink); }}',
         # buttons and selected chips sit on light ink in dark mode, so their text turns dark
         f'{D} .btn:not(.ghost), {D} .periods button[aria-pressed="true"], {D} .choices:not(.opts) button[aria-pressed="true"], {D} .roles button[aria-selected="true"], {D} .storynav a.on, {D} .tk-prov, {D} .skip {{ color: #121416; }}',
         f'{D} .btn.ghost {{ background: transparent; color: var(--ink); border-color: var(--ctl); }}',
         f'{D} .wl img, {D} .ai img {{ background: #fff; border-radius: 8px; padding: 4px 6px; }}',
         f'{D} .wl.has-logo img {{ height: 38px; }}',
         f'{D} .share-strip {{ background: #1a1d20; border: 1px solid var(--line); }}',
         f'{D} .top {{ background: rgba(18,20,22,.9); }}',
         f'{D} .mini:hover {{ box-shadow: 0 14px 30px -18px rgba(0,0,0,.8); }}',
         f'{D} .mv {{ background: linear-gradient(180deg, #1a1d20, #16181b); }}',
         f'{D} .ai .lm {{ color: var(--ink); }}',
         f'{D} input, {D} textarea, {D} select {{ background: #16181b; color: var(--ink); border-color: var(--ctl); }}',
         '/* DARK:END */']
css = css.rstrip() + '\n\n' + '\n'.join(block) + '\n'
open(P, 'w').write(css)
print(len(rules), 'dark rules')
